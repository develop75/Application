CREATE TABLE [dbo].[T_SYS_USER]
(
	[Id]					BIGINT PRIMARY KEY IDENTITY(1,1) NOT NULL,	
	ID_CITY    				BIGINT NOT NULL,
	ID_PROVINCE    			BIGINT NOT NULL,
	CA_EMAIL   				VARCHAR (100) UNIQUE NOT NULL,
	CA_PASSWORD   			VARCHAR (255) NOT NULL,
	CA_NAME   				VARCHAR (40) NOT NULL,	
	CA_SURNAME   			VARCHAR (40) NOT NULL,
	CA_CELL   				VARCHAR (20) NULL,
	CA_FISCAL_CODE   		VARCHAR (16) NOT NULL UNIQUE,
	CA_ADDRESS   			VARCHAR (255) NULL,	
	CA_CAP   				VARCHAR (6) NULL,
	CA_IBAN   				VARCHAR (34) NULL,
	CD_RATING   			INT NOT NULL DEFAULT 1,
	FL_SHIPPING 			BIT DEFAULT 0,
	FL_MARKETING			BIT DEFAULT 0,
	DA_CREATION   			DATETIME DEFAULT GETDATE(),
	DA_LAST_ACTIVITY   		DATETIME  NULL,
	CA_IPADDRESS   			VARCHAR (200) NULL,
	FL_ONLINE   			BIT DEFAULT 0,
	FL_ACTIVE   			BIT DEFAULT 1,
)
